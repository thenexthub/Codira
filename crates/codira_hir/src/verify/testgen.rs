//! Functionality:
//! - Turns a refuted proof obligation into a runnable `@test` that calls the
//!   function with the counterexample Z3 found.
//!
//! The test is a child module of the function's own module (so it can
//! import a private function from `super`), written to
//! `tests/generated/<module path.><function>_counterexample.code`;
//! `codira test` mounts each such file back under that module. What the test
//! asserts depends on what was refuted:
//!
//! * a postcondition or a refined return type is *checked*: the test returns
//!   the clause evaluated on the actual result, so it fails exactly while the
//!   bug is there;
//! * anything else (a callee's precondition, a division) has no value the test
//!   can inspect from outside; the test makes the call and is expected to trap
//!   or misbehave, as the comment above it says.

use codira_syntax::SyntaxNodePtr;

use super::{refinement, Counterexample, Obligation, ObligationKind, Verdict};
use crate::{code_model::Function, in_file::InFile, HirDatabase, Module};

/// A generated counterexample test.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedTest {
    /// File name inside `tests/generated/`.
    pub file_name: String,
    /// Path segments of the module the test belongs under (the function's
    /// module; empty for the package root).
    pub module_path: Vec<String>,
    pub contents: String,
}

/// The first line of every generated file; `codira check` only ever
/// rewrites or deletes files that start with it.
pub const GENERATED_MARKER: &str =
    "// @generated by `codira check` from a Z3 counterexample. Do not edit.";

/// The module path of `module`, root first.
pub fn module_path(db: &dyn HirDatabase, module: Module) -> Vec<String> {
    let mut path: Vec<String> = module
        .path_to_root(db)
        .into_iter()
        .filter_map(|m| m.name(db))
        .collect();
    path.reverse();
    path
}

/// The file name a generated test for a function in `module_path` named
/// `function` gets.
pub fn file_name(module_path: &[String], function: &str) -> String {
    let mut name = String::new();
    for segment in module_path {
        name.push_str(segment);
        name.push('.');
    }
    name.push_str(function);
    name.push_str("_counterexample.code");
    name
}

/// The module path a generated file belongs under, read back from its name:
/// the inverse of [`file_name`]. `None` for a name that is not one.
pub fn module_path_of_file(file_name: &str) -> Option<Vec<String>> {
    let stem = file_name.strip_suffix("_counterexample.code")?;
    let mut segments: Vec<String> = stem.split('.').map(str::to_string).collect();
    segments.pop()?;
    Some(segments)
}

fn location(db: &dyn HirDatabase, site: &InFile<SyntaxNodePtr>) -> String {
    let path = db.file_relative_path(site.file_id);
    let line_col = db
        .line_index(site.file_id)
        .line_col(site.value.range().start());
    format!("{}:{}:{}", path, line_col.line + 1, line_col.col_utf16 + 1)
}

/// The counterexample test for `func`, if it has a refuted obligation and a
/// signature a test can call: a free function whose parameters are all
/// integers or booleans.
pub fn counterexample_test(db: &dyn HirDatabase, func: Function) -> Option<GeneratedTest> {
    if func.data(db).has_self_param() || !func.data(db).generic_params().is_empty() {
        return None;
    }
    let report = db.verify_function(func);
    if report.params.iter().any(|p| p.ty.is_none()) {
        return None;
    }
    let refuted: Vec<(&Obligation, &Counterexample)> = report
        .obligations
        .iter()
        .filter_map(|o| match &o.verdict {
            Verdict::Refuted(cex) => Some((o, cex)),
            _ => None,
        })
        .collect();
    // A checked result first: that test fails exactly while the bug is there.
    let (obligation, cex) = refuted
        .iter()
        .find(|(o, _)| {
            matches!(
                o.kind,
                ObligationKind::Postcondition | ObligationKind::RefinedReturn
            )
        })
        .or_else(|| refuted.first())
        .copied()?;
    if cex.inputs.len() != report.params.len() {
        return None;
    }

    let name = func.name(db).to_string();
    let module_path = module_path(db, func.module(db));
    let mut out = String::new();
    out.push_str(GENERATED_MARKER);
    out.push('\n');
    out.push_str("// It is rewritten while the obligation stays refuted and deleted once\n");
    out.push_str("// the obligation is proven.\n//\n");
    out.push_str(&format!("// Violated: {}\n", obligation.message()));
    out.push_str(&format!("//   at {}\n", location(db, &obligation.site)));
    out.push_str(&format!("// Counterexample: {}\n", cex.call(&name)));
    if !cex.at_site.is_empty() {
        let values: Vec<String> = cex
            .at_site
            .iter()
            .map(|(n, v)| format!("{n} = {v}"))
            .collect();
        out.push_str(&format!("// At the failing point: {}\n", values.join(", ")));
    }

    let bindings: String = cex
        .inputs
        .iter()
        .map(|(param, value)| format!("    let {param} = {};\n", value.to_source()))
        .collect();
    let args: Vec<&str> = cex.inputs.iter().map(|(p, _)| p.as_str()).collect();
    let call = format!("{name}({})", args.join(", "));

    let checked_clause = match obligation.kind {
        ObligationKind::Postcondition if !args.contains(&"result") => {
            Some(("result".to_string(), obligation.clause.clone()))
        }
        ObligationKind::RefinedReturn => refinement::return_refinement(db, func)
            .map(|r| (r.binder, r.text))
            .filter(|(binder, _)| !args.contains(&binder.as_str())),
        _ => None,
    };

    // A module-qualified call is not an expression form the language has;
    // the function is imported from the parent module instead, which also
    // reaches a private function (a child module sees its parent's items).
    out.push('\n');
    out.push_str(&format!("import super.{name};\n\n"));
    if let Some((binder, clause)) = checked_clause {
        out.push_str("@test\n");
        out.push_str(&format!("public func {name}_counterexample() -> bool {{\n"));
        out.push_str(&bindings);
        out.push_str(&format!("    let {binder} = {call};\n"));
        out.push_str(&format!("    {clause}\n"));
    } else {
        out.push_str("// Expected to fail at run time: this input reaches the obligation above.\n");
        out.push_str("@test\n");
        out.push_str(&format!("public func {name}_counterexample() {{\n"));
        out.push_str(&bindings);
        out.push_str(&format!("    {call};\n"));
    }
    out.push_str("}\n");

    Some(GeneratedTest {
        file_name: file_name(&module_path, &name),
        module_path,
        contents: out,
    })
}
